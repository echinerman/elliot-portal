    await page.evaluate(() => { window.fixtureFailWrite = false; });
    await page.evaluate(() => { window.fixtureLoseCommitResponse = true; });
    await page.locator('#communication-send').click();
    await page.waitForFunction(() => document.getElementById('communication-send-status').textContent.includes('Synthetic lost commit response'));
