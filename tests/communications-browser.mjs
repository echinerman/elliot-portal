    await page.waitForFunction(() => window.fixtureData.get('communication_notifications/notice-fixture').status === 'queued');
    assert.equal(await page.evaluate(() => [...window.fixtureData.keys()].filter(key => key.startsWith('communication_outbox/')).length), 2, 'phone alert retry must not queue email');
    await page.locator('[data-save-history]').first().click();
