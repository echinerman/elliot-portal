import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { createFixtureServer } from './communications-browser-server.mjs';

const { chromium } = createRequire(import.meta.url)('playwright');
const server = createFixtureServer();
await new Promise(resolve => server.listen(4329, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept());
await mkdir('.impeccable/review', { recursive: true });
const outboxCount = () => page.evaluate(() => [...window.fixtureData.keys()].filter(key => key.startsWith('communication_outbox/')).length);
let run = 0;
const openCompose = async () => {
    await page.goto(`http://127.0.0.1:4329/admin.html?fixture=${++run}#inbox/compose/prospect-fixture-01`);
    await page.locator('#prospect-body').waitFor();
    await page.evaluate(() => document.fonts.ready);
};
try {
    await openCompose();
    assert.match(await page.locator('#prospect-body').inputValue(), /Hi Alex,/);
    assert.equal(await outboxCount(), 0);
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.copiedProspectText = text; } } }));
    await page.locator('#prospect-body').fill('Hi Alex, want a hand getting set up?');
    await page.locator('#prospect-copy').click();
    assert.equal(await page.evaluate(() => window.copiedProspectText), 'Hi Alex, want a hand getting set up?');
    assert.equal(await outboxCount(), 0, 'copy must not send or create a conversation');
    assert.equal(await page.evaluate(() => window.fixtureData.get('strong8k_private/prospect-fixture-01').prospect_status), 'prospect');
    await page.screenshot({ path: '.impeccable/review/prospect-compose-desktop.png', fullPage: true });
    await page.locator('#prospect-compose-back').click();
    await page.locator('#user-workspace').waitFor({ state: 'visible' });
    await page.evaluate(() => { location.hash = '#inbox/compose/prospect-fixture-01'; });
    await page.locator('#prospect-body').waitFor();
    assert.equal(await page.locator('#prospect-body').inputValue(), 'Hi Alex, want a hand getting set up?');
    await page.evaluate(() => { window.fixtureLoseCommitResponse = true; });
    await page.locator('#prospect-send').click();
    await page.waitForFunction(() => document.getElementById('communication-send-status')?.textContent.includes('lost commit response'));
    assert.equal(await outboxCount(), 1);
    assert.equal(await page.locator('#prospect-body').getAttribute('readonly'), '');
    await page.locator('#prospect-send').click();
    await page.locator('#communication-reply').waitFor();
    assert.equal(await outboxCount(), 1, 'retry after uncertain transaction must not duplicate');
    assert.match(await page.locator('#communication-timeline').innerText(), /Queued/);

    await openCompose();
    await page.evaluate(() => { window.fixtureData.get('communication_config/runtime').sending_enabled = false; });
    await page.locator('#prospect-send').click();
    await page.waitForFunction(() => document.getElementById('communication-send-status').textContent.includes('sending is paused'));
    assert.equal(await outboxCount(), 0);
    await page.locator('#prospect-discard').click();
    await page.locator('#user-workspace').waitFor({ state: 'visible' });
    await openCompose();
    await page.evaluate(() => { window.fixtureData.get('users/prospect-fixture-01').email = 'changed@example.com'; });
    await page.locator('#prospect-send').click();
    await page.waitForFunction(() => document.getElementById('communication-send-status').textContent.includes('email changed'));
    assert.equal(await outboxCount(), 0);
    await openCompose();
    await page.evaluate(() => { window.fixtureData.get('strong8k_private/prospect-fixture-01').prospect_status = 'customer'; });
    await page.locator('#prospect-send').click();
    await page.waitForFunction(() => document.getElementById('communication-send-status').textContent.includes('no longer a confirmed prospect'));
    assert.equal(await outboxCount(), 0);
    await openCompose();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => document.getElementById('admin-room-rail').getBoundingClientRect().right <= 0);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: '.impeccable/review/prospect-compose-mobile.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: prospect draft, copy-only, navigation retention, atomic queue/retry, paused sending, stale recipient, conversion guard, and mobile layout. Synthetic only.');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
